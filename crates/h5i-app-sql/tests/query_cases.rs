//! The reference evaluator against the Lean definitions: random reads and
//! what `eval::rows` returns for them, written as `#guard`s on
//! `H5iAppLib.Query.Read.rows` in `H5iAppLibTests/QueryCases.lean`, which the
//! Lean build checks. This test fails if that file is not what the
//! evaluator says; `H5I_APP_BLESS=1` rewrites it.

use h5i_app_sql::eval::{self, cases};
use h5i_app_sql::{Pred, Read, Val, Window};
use std::fmt::Write;

const PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../h5i-app-core/proofs/H5iAppLibTests/QueryCases.lean");

fn val(v: &Val) -> String {
    match v {
        Val::Int(i) => format!("(.i {i})"),
        Val::Bytes(b) | Val::Text(b) => format!("(.b {b:?})"),
        Val::Bool(b) => format!("(.i {})", i64::from(*b)),
        Val::Null => ".null".into(),
    }
}

fn row(r: &[Val]) -> String {
    format!("[{}]", r.iter().map(val).collect::<Vec<_>>().join(", "))
}

fn rows(rs: &[Vec<Val>]) -> String {
    format!("[{}]", rs.iter().map(|r| row(r)).collect::<Vec<_>>().join(", "))
}

fn window(w: &Window) -> String {
    let lim = match w.limit {
        None => "none".to_string(),
        Some(n) => format!("some {n}"),
    };
    format!("{{ desc := {}, offset := {}, limit := {lim} }}", w.desc, w.offset)
}

fn pred(p: &Pred) -> String {
    match p {
        Pred::All => ".all".into(),
        Pred::Eq { col, val: v } => format!("(.eq {col} {})", val(v)),
        Pred::In { col, table, pred: q, of, window: w } => format!("(.isIn {col} {table} {} {of} {})", pred(q), window(w)),
        Pred::And(a, b) => format!("(.and {} {})", pred(a), pred(b)),
        Pred::Or(a, b) => format!("(.or {} {})", pred(a), pred(b)),
    }
}

fn read(q: &Read) -> String {
    format!("{{ table := {}, pred := {}, window := {} }}", q.table, pred(&q.pred), window(&q.window))
}

fn render() -> String {
    let mut out = String::from(
        "import H5iAppLib.Query
/-!
Generated by `crates/h5i-app-sql/tests/query_cases.rs` (`H5I_APP_BLESS=1`
rewrites it); do not edit. Each `#guard` is a random read and the rows the
Rust reference evaluator (`h5i_app_sql::eval`) returns for it: building this
file checks that `H5iAppLib.Query.Read.rows` agrees. The same evaluator is
compared with PostgreSQL in `crates/h5i-app-pg/src/reads_test.rs`.
-/

namespace H5iAppLibTests.QueryCases

open H5iAppLib.Query

inductive TV where
  | i (n : Int)
  | b (s : List Nat)
  | null
deriving DecidableEq

",
    );
    let mut r = cases::Rng(7);
    for case in 0..40 {
        let tabs = cases::tables(&mut r);
        writeln!(out, "def tabs{case} : H5iAppLib.Sql.Tables TV").unwrap();
        for (i, t) in tabs.iter().enumerate() {
            writeln!(out, "  | {i} => {}", rows(t)).unwrap();
        }
        writeln!(out, "  | _ => []\n").unwrap();
        for _ in 0..5 {
            let q = cases::read(&mut r);
            let want = eval::rows(&tabs, &q);
            writeln!(out, "#guard Read.rows tabs{case} ({} : Read TV) = {}", read(&q), rows(&want)).unwrap();
        }
        out.push('\n');
    }
    out.push_str("end H5iAppLibTests.QueryCases\n");
    out
}

#[test]
fn query_cases_lean_is_current() {
    let text = render();
    if std::env::var("H5I_APP_BLESS").is_ok() {
        std::fs::write(PATH, &text).unwrap();
        return;
    }
    let old = std::fs::read_to_string(PATH).unwrap_or_default();
    assert!(old == text, "{PATH} is stale: rerun with H5I_APP_BLESS=1");
}
