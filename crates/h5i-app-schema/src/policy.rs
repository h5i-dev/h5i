//! `schema!`'s `policy` block: who may write and see which rows, declared per
//! table, as a plain-Rust `h5i_app_std::authz::Policy` in the Aeneas subset.
//!
//! ```ignore
//! h5i_app_schema::schema! {
//!     mapping notes_tables for notes_kernel, writes Write, lean "../proofs/generated/Schema.lean";
//!
//!     policy Notes {
//!         principal Principal.user;
//!         write Write;
//!         row Row;
//!         admin members.admin;
//!         table Member in members key user: u64 {
//!             put PutMember del DelMember row OfMember owner user
//!             write [admin, first] visible [owner, admin]
//!         }
//!         table Note in notes key id: u64 {
//!             put PutNote del DelNote row OfNote owner owner
//!             write [owner, admin] visible [public, owner, admin]
//!         }
//!     }
//!     // the snapshot and the row structs, as without a policy
//! }
//! ```
//!
//! The meaning, with `u` the principal's user field (`Principal.user`):
//!
//! - `admin members.admin`: `u` is an admin if the `members` row with key `u`
//!   has `admin` set.
//! - A put of row `x` whose key is not stored creates it: allowed if one of the
//!   `write` atoms allows it. `owner`: `x.owner == u`. `admin`: `u` is an
//!   admin. `first`: the table is empty.
//! - A put of a row whose key is stored replaces `old`: the owner column never
//!   changes (`x.owner == old.owner`), and one atom must allow it. `owner`:
//!   `old.owner == u`. `admin`: `u` is an admin. `first`: never.
//! - A delete (`del`, carrying the key) needs a stored row and one atom as for
//!   a replacement; a key that is not stored is refused.
//! - `visible`: one atom. `all`: every row. `owner`: `x.owner == u`.
//!   `admin`: `u` is an admin. Any other name is a `bool` column of the row.
//! - `stored`: the row is stored under its key exactly as given.
//!
//! It writes `pub struct <Policy>`, its `Policy` impl, and a `policy` module:
//! `policy::permits`, `visible`, `stored`, `view` (the snapshot with each
//! table's visible rows: every snapshot field must be a policy table),
//! `is_admin`, and per table `policy::<field>::{find, put, del, visible,
//! stored, view}`. The `Write` and `Row` enums are the app's; a variant without
//! a policy does not compile. With `lean "..."`, the generated Lean schema
//! gets `<krate>.PolicySpec`, the same meaning stated over lists from this
//! block (never from the Rust it generates), and theorems that the extracted
//! `policy::permits`, `visible` and `stored` compute it.
//!
//! The generator is part of the reviewed surface of an `[authz]` app that
//! uses it (`docs/design/design-app-authz.md`, "A policy from the schema").

/// The `policy` block: the `Policy` impl and the `policy` module.
#[doc(hidden)]
#[macro_export]
macro_rules! __policy {
    (
        $snap:ident $pname:ident {
            principal $p:ident . $uf:ident ;
            write $w:ident ;
            row $d:ident ;
            $( admin $atf:ident . $af:ident ; )?
            $( table $t:ident in $tf:ident key $key:ident : $kt:ty {
                put $put:ident $( del $del:ident )? row $rv:ident $( owner $ow:ident )?
                write [ $($wa:ident),+ $(,)? ] visible [ $($va:ident),+ $(,)? ]
            } )+
        }
    ) => {
        /// The policy `schema!`'s `policy` block declares. Its `Policy` impl
        /// calls the generated `policy` module.
        pub struct $pname;

        impl ::h5i_app_std::authz::Policy<$p, $snap, $w, $d> for $pname {
            fn permits(actor: &$p, s: &$snap, w: &$w) -> bool {
                policy::permits(actor, s, w)
            }

            fn visible(actor: &$p, s: &$snap, d: &$d) -> bool {
                policy::visible(actor, s, d)
            }

            fn stored(s: &$snap, d: &$d) -> bool {
                policy::stored(s, d)
            }
        }

        /// Generated by `schema!` from its `policy` block: plain Rust for
        /// Aeneas. `PolicySpec` in the generated Lean schema states what each
        /// function computes.
        #[allow(clippy::nonminimal_bool, clippy::overly_complex_bool_expr, clippy::ptr_arg)]
        pub mod policy {
            #[allow(unused_imports)]
            use super::*;

            $(
                /// `admin`: the principal's own row has the admin column set.
                pub fn is_admin(s: &$snap, actor: &$p) -> bool {
                    match $atf::find(&s.$atf, actor.$uf) {
                        Some(r) => r.$af,
                        None => false,
                    }
                }
            )?

            $( $crate::__policy_table! { [$snap $p $uf] $t $tf $key [$kt] [$($ow)?] [$($wa)+] [$($va)+] } )+

            /// May `actor` make write `w` in `s`?
            pub fn permits(actor: &$p, s: &$snap, w: &$w) -> bool {
                match w {
                    $( $w::$put(x) => $tf::put(actor, s, x), )+
                    $( $( $w::$del(k) => $tf::del(actor, s, $tf::find(&s.$tf, *k)), )? )+
                }
            }

            /// May `actor` see row `d` in `s`?
            pub fn visible(actor: &$p, s: &$snap, d: &$d) -> bool {
                match d {
                    $( $d::$rv(x) => $tf::visible(actor, s, x), )+
                }
            }

            /// Is `d` stored in `s`, exactly as given?
            pub fn stored(s: &$snap, d: &$d) -> bool {
                match d {
                    $( $d::$rv(x) => $tf::stored(s, x), )+
                }
            }

            /// The part of `s` that `actor` may see: each table's visible rows.
            /// Every snapshot field must be a policy table (the struct
            /// literal does not compile otherwise), so nothing is copied
            /// unjudged.
            pub fn view(actor: &$p, s: &$snap) -> $snap {
                $snap { $( $tf: $tf::view(actor, s), )+ }
            }
        }
    };
}

/// One table of a `policy` block: `policy::<field>`.
#[doc(hidden)]
#[macro_export]
macro_rules! __policy_table {
    ([$snap:ident $p:ident $uf:ident] $t:ident $tf:ident $key:ident [$kt:ty] $owg:tt [$($wa:ident)+] [$($va:ident)+]) => {
        #[allow(unused_variables)]
        pub mod $tf {
            #[allow(unused_imports)]
            use super::*;

            /// The stored row with key `k`, if any.
            pub fn find(v: &Vec<$t>, k: $kt) -> Option<$t> {
                let mut i = 0;
                while i < v.len() {
                    if v[i].$key == k {
                        return Some(v[i].clone());
                    }
                    i += 1;
                }
                None
            }

            /// May `actor` store `x`: create it, or replace the row with its key?
            pub fn put(actor: &$p, s: &$snap, x: &$t) -> bool {
                match find(&s.$tf, x.$key) {
                    None => $( $crate::__policy_create!($wa $owg actor s x $uf $tf) )||+,
                    Some(old) => $crate::__policy_keep!($owg x old) && ($( $crate::__policy_modify!($wa $owg actor s old $uf) )||+),
                }
            }

            /// May `actor` delete `found`, the row stored under the key?
            pub fn del(actor: &$p, s: &$snap, found: Option<$t>) -> bool {
                match found {
                    None => false,
                    Some(old) => $( $crate::__policy_modify!($wa $owg actor s old $uf) )||+,
                }
            }

            /// May `actor` see `x`?
            pub fn visible(actor: &$p, s: &$snap, x: &$t) -> bool {
                $( $crate::__policy_visible!($va $owg actor s x $uf) )||+
            }

            /// Is `x` stored under its key, exactly as given?
            pub fn stored(s: &$snap, x: &$t) -> bool {
                match find(&s.$tf, x.$key) {
                    Some(r) => r == *x,
                    None => false,
                }
            }

            /// The rows `actor` may see, in stored order.
            pub fn view(actor: &$p, s: &$snap) -> Vec<$t> {
                let mut out = Vec::new();
                let mut i = 0;
                while i < s.$tf.len() {
                    if visible(actor, s, &s.$tf[i]) {
                        out.push(s.$tf[i].clone());
                    }
                    i += 1;
                }
                out
            }
        }
    };
}

/// A `write` atom, for a row that is not stored yet.
#[doc(hidden)]
#[macro_export]
macro_rules! __policy_create {
    (owner [$ow:ident] $a:ident $s:ident $x:ident $uf:ident $tf:ident) => {
        $x.$ow == $a.$uf
    };
    (admin $owg:tt $a:ident $s:ident $x:ident $uf:ident $tf:ident) => {
        is_admin($s, $a)
    };
    (first $owg:tt $a:ident $s:ident $x:ident $uf:ident $tf:ident) => {
        $s.$tf.len() == 0
    };
}

/// A `write` atom, for the stored row `old` a write replaces or deletes.
#[doc(hidden)]
#[macro_export]
macro_rules! __policy_modify {
    (owner [$ow:ident] $a:ident $s:ident $old:ident $uf:ident) => {
        $old.$ow == $a.$uf
    };
    (admin $owg:tt $a:ident $s:ident $old:ident $uf:ident) => {
        is_admin($s, $a)
    };
    (first $owg:tt $a:ident $s:ident $old:ident $uf:ident) => {
        false
    };
}

/// A replacement keeps the owner column.
#[doc(hidden)]
#[macro_export]
macro_rules! __policy_keep {
    ([$ow:ident] $x:ident $old:ident) => {
        $x.$ow == $old.$ow
    };
    ([] $x:ident $old:ident) => {
        true
    };
}

/// A `visible` atom.
#[doc(hidden)]
#[macro_export]
macro_rules! __policy_visible {
    (all $owg:tt $a:ident $s:ident $x:ident $uf:ident) => {
        true
    };
    (owner [$ow:ident] $a:ident $s:ident $x:ident $uf:ident) => {
        $x.$ow == $a.$uf
    };
    (admin $owg:tt $a:ident $s:ident $x:ident $uf:ident) => {
        is_admin($s, $a)
    };
    ($c:ident $owg:tt $a:ident $s:ident $x:ident $uf:ident) => {
        $x.$c
    };
}

/// With a `policy` block and `lean "..."`: append `PolicySpec` to the Lean schema.
#[doc(hidden)]
#[macro_export]
macro_rules! __lean_policy {
    ($text:ident $krate:ident []) => {};
    (
        $text:ident $krate:ident [
            $snap:ident $pname:ident {
                principal $p:ident . $uf:ident ;
                write $w:ident ;
                row $d:ident ;
                $( admin $atf:ident . $af:ident ; )?
                $( table $t:ident in $tf:ident key $key:ident : $kt:ty {
                    put $put:ident $( del $del:ident )? row $rv:ident $( owner $ow:ident )?
                    write [ $($wa:ident),+ $(,)? ] visible [ $($va:ident),+ $(,)? ]
                } )+
            }
        ]
    ) => {
        let decl = $crate::lean::PolicyDecl {
            krate: stringify!($krate),
            snapshot: stringify!($snap),
            principal: stringify!($p),
            user: stringify!($uf),
            write: stringify!($w),
            row: stringify!($d),
            admin: $crate::__lean_policy_admin!($($atf $af)?),
            tables: ::std::vec![ $( $crate::lean::PolicyTable {
                row_type: stringify!($t),
                field: stringify!($tf),
                key: stringify!($key),
                key_type: ::std::any::type_name::<$kt>(),
                put: stringify!($put),
                del: $crate::__lean_opt!($($del)?),
                variant: stringify!($rv),
                owner: $crate::__lean_opt!($($ow)?),
                write: ::std::vec![$(stringify!($wa)),+],
                visible: ::std::vec![$(stringify!($va)),+],
            }, )+ ],
        };
        $text.push_str(&$crate::lean::render_policy(&decl));
    };
}

#[doc(hidden)]
#[macro_export]
macro_rules! __lean_policy_admin {
    () => {
        ::std::option::Option::None
    };
    ($atf:ident $af:ident) => {
        ::std::option::Option::Some((stringify!($atf), stringify!($af)))
    };
}
