// Fail early, and with an actionable message, when web/package-lock.json was
// written by an npm that recorded only its own machine's optional binaries.
//
// Rollup (via Vite) ships its native code as per-platform optional packages.
// npm 9 writes a lockfile containing only the ones matching the machine that
// generated it; npm 10 records every variant. So a lockfile regenerated from
// scratch on, say, an arm64 laptop installs cleanly there and then dies on an
// x64 CI runner with `Cannot find module @rollup/rollup-linux-x64-gnu` and a
// stack trace into node_modules — a message that says nothing about the actual
// cause, which is three commits away in a file nobody was looking at.
//
// This turns that into one line naming the fix. Run from `web/`:
//
//     node ../scripts/check-lockfile-platforms.mjs

import { readFileSync } from "node:fs";

// The platforms h5i builds the bundle on. CI runs the Linux one; the others are
// here so a contributor on a Mac or on WSL/arm64 is covered by the same check.
const REQUIRED = [
  "@rollup/rollup-linux-x64-gnu",
  "@rollup/rollup-linux-arm64-gnu",
  "@rollup/rollup-darwin-arm64",
  "@rollup/rollup-darwin-x64",
];

const lock = JSON.parse(readFileSync("package-lock.json", "utf8"));
const packages = Object.keys(lock.packages ?? {});
const missing = REQUIRED.filter(
  (pkg) => !packages.includes(`node_modules/${pkg}`),
);

if (missing.length > 0) {
  const err = process.env.GITHUB_ACTIONS ? "::error::" : "error: ";
  console.error(
    `${err}web/package-lock.json is missing platform binaries: ${missing.join(", ")}`,
  );
  console.error(
    "\nThis lockfile was generated by an npm that only records the platform it " +
      "ran on (npm 9 and older). `npm ci` will fail on any other platform, " +
      "including this runner.\n\nRegenerate it with npm 10+:\n\n" +
      "    cd web && rm -rf node_modules package-lock.json && npx npm@10 install\n\n" +
      "then commit package-lock.json. `npm ci` is safe to run with any npm " +
      "version once the lockfile is correct.",
  );
  process.exit(1);
}

console.log(
  `package-lock.json covers all ${REQUIRED.length} build platforms ` +
    `(lockfileVersion ${lock.lockfileVersion}).`,
);
